#!/usr/bin/env python3
"""Build the /free-test/sample report from the a11y-audit free-check template.

Renders a fictional result for "City of Example, FL" (example.org), population over 50,000, through
free_test/emails.py report_parts, the same code that writes every real report,
adds a "Sample report" line under the heading, and writes the HTML as a string
module the page shows in a frame (app/free-test/sample/report.ts). Every number
below is made up and no real organization is named. It also writes the /free-test
thumbnail (public/thumbs/free-test-sample.png): the top of the report frame, from
the header down through the impact table, 440px wide (2x for a 220px slot), via
Playwright's Chromium in light mode.

    python3 scripts/build_free_test_sample.py      # after a template change in ~/Code/a11y-audit
"""
import json
import pathlib
import sys
import time

from playwright.sync_api import sync_playwright

A11Y = pathlib.Path.home() / "Code/a11y-audit"
sys.path.insert(0, str(A11Y))
from free_test import deadlines, emails  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/free-test/sample/report.ts"
THUMB = ROOT / "public/thumbs/free-test-sample.png"
SITE = "https://example.org/"
WHEN = time.mktime((2026, 10, 19, 9, 0, 0, 0, 0, -1))
# The fictional city is on no deadline roster, so it gets the one-date line a city
# on record gets, with the reason in the same form as deadlines._reason.
DEADLINE = ("April 26, 2027", "the City of Example's 2020 population is over 50,000")
deadlines.lookup = lambda origin: DEADLINE if "example.org" in origin else None

SAMPLE = ("Sample report. The City of Example, FL and example.org are fictional, and every number "
          "here is made up. A real report has this form.")

PAGES = ["", "pay-utility-bill", "permits/apply", "contact", "agendas-minutes", "jobs", "parks/reservations",
         "police/records-request", "city-clerk", "news"]
# (tagged, extra findings) for each of the 10 PDFs read
DOCS = [(False, {"no_title": True}), (False, {"scanned_no_text": True, "no_title": True}), (False, {}),
        (False, {"no_title": True}), (False, {}), (False, {}), (True, {"no_headings": True}),
        (True, {"no_headings": True, "tables_without_headers": 1, "no_title": True}), (True, {}), (True, {})]

documents = [{"url": f"{SITE}files/doc-{i}.pdf", "status": "read", "tagged": t, **x} for i, (t, x) in enumerate(DOCS)]
df = {"read": len(documents), "linked": 14, **dict.fromkeys(emails.DOC_KEYS, 0), "offsite": 0, "offsite_hosts": []}
for d in documents:
    df["untagged"] += not d["tagged"]
    for k in ("scanned_no_text", "no_headings", "no_title"):
        df[k] += bool(d.get(k))
    df["tables_without_headers"] += d.get("tables_without_headers", 0)

result = {
    "status": "ok", "site": SITE,
    "pages": [{"url": SITE + p, "status": "scanned", "axe": "ran", "chosen": "priority" if i else "home"}
              for i, p in enumerate(PAGES)],
    "documents": documents,
    "counts_by_impact": {"critical": 7, "serious": 214, "moderate": 18, "minor": 0},
    "top_issues": [
        {"rule": "image-alt", "help": "Images must have alternative text", "impact": "critical",
         "wcag": ["1.1.1"], "pages": 3, "instances": 7},
        {"rule": "color-contrast", "help": "Elements must meet minimum color contrast ratio thresholds",
         "impact": "serious", "wcag": ["1.4.3"], "pages": 10, "instances": 168},
        {"rule": "link-name", "help": "Links must have discernible text", "impact": "serious",
         "wcag": ["2.4.4", "4.1.2"], "pages": 8, "instances": 31}],
    "skip_link": {"present": False},
    "measured": {"pages": 10, "contrast_elements": 0, "images_without_alt": 0, "no_lang_pages": 0,
                 "no_skip_link_pages": 10, "main_landmark_pages": 6},
    "document_findings": df,
}

subject, blocks = emails.report_parts(result, WHEN, "city")
_, _, html = emails._email(subject, subject, blocks)
html = html.replace("</h1></td></tr>", "</h1></td></tr>" + emails._row(emails._inner(("panel", [("p", SAMPLE)]))), 1)
# Links leave the frame for the page around it.
html = html.replace("<head>", '<head><base target="_top">', 1)
for real in ("Example, FL",):
    assert html.count(real) == 1
OUT.write_text("// Generated by scripts/build_free_test_sample.py from a11y-audit free_test/emails.py. Don't edit.\n"
               f"export const SUBJECT = {json.dumps(subject)};\n"
               f"export const REPORT = {json.dumps(html, ensure_ascii=False)};\n", encoding="utf-8")
print(f"wrote {OUT} ({len(html):,} bytes): {subject}")

# The frame is the email's 600px column; the impact table is its first table that isn't layout.
with sync_playwright() as pw:
    browser = pw.chromium.launch()
    page = browser.new_page(viewport={"width": 640, "height": 1200}, device_scale_factor=440 / 600,
                            color_scheme="light")
    page.set_content(html)
    x, y, w, bottom = page.evaluate("""() => {
      const f = document.querySelector('table[style*="max-width:600px"]').getBoundingClientRect();
      const t = document.querySelector('table:not([role])').getBoundingClientRect();
      return [f.x, f.y, f.width, t.bottom + 8];
    }""")
    page.screenshot(path=str(THUMB), clip={"x": x, "y": y, "width": w, "height": bottom - y})
    browser.close()
print(f"wrote public/thumbs/{THUMB.name}")
